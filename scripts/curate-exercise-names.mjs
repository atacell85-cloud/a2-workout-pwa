const missing = [];
dataset.exercises = dataset.exercises.map(exercise => {
  const nameTr = names[exercise.id];
  if (!nameTr) missing.push(exercise.id);
  const aliases = Array.from(new Set([...(exercise.aliases || []), exercise.nameTr, exercise.nameEn].filter(Boolean)));
  return nameTr ? { ...exercise, nameTr, aliases } : { ...exercise, aliases };
});

if (missing.length) {
  throw new Error(`Missing Turkish names for: ${missing.join(', ')}`);
}

dataset.datasetVersion = '1.1.1';
dataset.status = 'curated';
dataset.exerciseCount = dataset.exercises.length;

writeFileSync(file, `${JSON.stringify(dataset, null, 2)}\n`);
console.log(`Updated ${dataset.exercises.length} exercise names.`);
